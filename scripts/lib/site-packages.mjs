import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { lstat, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const require = createRequire(import.meta.url);
const { parse } = require('@babel/parser');
const traverseModule = require('@babel/traverse');
const traverse = traverseModule.default || traverseModule;
const slash = value => value.replace(/\\/g, '/');
const hash = value => createHash('sha256').update(value).digest('hex');
const json = value => `${JSON.stringify(value, null, 2)}\n`;
const sourceExtensions = ['.js', '.jsx', '.mjs', '.cjs', '.ts', '.tsx', '.json', '.css', '.svg'];
const codePattern = /\.(?:[cm]?js|jsx|tsx?)$/i;
const forbiddenSource = /(?:^|\/)(?:__tests__|__fixtures__|tests?|fixtures?|test-support|node_modules|\.git|\.codex|\.agents|\.aws)(?:\/|$)|(?:^|\/)(?:\.env(?:\.|$)|credentials?(?:\.|$))|(?:^|\/)(?:setupTests|[^/]+\.(?:test|spec))\.[^/]+$/i;
const engineSiteSource = /(?:^|\/)(?:sites|themes?|artwork)(?:\/|$)|(?:^|\/)config(?:[-.][^/]*)?\.(?:json|js|jsx|mjs|cjs)$/i;

function check(condition, message) {
  if (!condition) throw new Error(message);
}

function relativePath(value, label = 'path') {
  check(typeof value === 'string' && value.length > 0 && !value.includes('\\') && !path.posix.isAbsolute(value) && !/^[a-z]:/i.test(value), `Invalid ${label}: expected a portable relative path`);
  check(value.split('/').every(part => part && part !== '.' && part !== '..' && !/[. ]$/.test(part)) && !/[\x00-\x1f<>:"|?*]/.test(value), `Invalid ${label}: path escape or nonportable segment`);
  return value;
}

function within(root, candidate) {
  const relative = path.relative(path.resolve(root), path.resolve(candidate));
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative));
}

// Check every existing ancestor: realpath alone would silently accept a source symlink.
export async function assertNoSymlinks(filename) {
  const absolute = path.resolve(filename);
  let current = path.parse(absolute).root;
  for (const part of absolute.slice(current.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    try {
      const info = await lstat(current);
      check(!info.isSymbolicLink(), `Symlink is not an input/output boundary: ${current}`);
    } catch (error) {
      if (error.code === 'ENOENT') break;
      throw error;
    }
  }
}

async function fileAt(root, relative) {
  relativePath(relative);
  const filename = path.resolve(root, relative);
  check(within(root, filename), `Path escapes package: ${relative}`);
  await assertNoSymlinks(filename);
  check((await lstat(filename)).isFile(), `Input is not a regular file: ${relative}`);
  return filename;
}

async function freshDirectory(root) {
  check(path.isAbsolute(root), 'Artifact/assembly output must be absolute');
  await assertNoSymlinks(root);
  try {
    await lstat(root);
    throw new Error(`Output must be a fresh directory: ${root}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  await mkdir(root, { recursive: true });
}

async function write(root, relative, content) {
  const target = path.resolve(root, relativePath(relative));
  check(within(root, target), `Output escapes package: ${relative}`);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, content);
}

function validateRecords(manifest, artifact = false) {
  check(manifest?.schemaVersion === 1 && typeof manifest.name === 'string' && typeof manifest.version === 'string', 'Invalid engine manifest identity/schema');
  check(Array.isArray(manifest.core) && manifest.features && typeof manifest.features === 'object' && !Array.isArray(manifest.features), 'Invalid engine core/features');
  check(Array.isArray(manifest.publicFiles) && Array.isArray(manifest.tooling), 'Invalid engine publicFiles/tooling');
  const targets = new Set(['LICENSE', 'package.json', 'engine.json']);
  const sources = new Set();
  const components = new Set();
  const groups = [['engine:core', manifest.core], ...Object.entries(manifest.features).map(([name, files]) => {
    check(/^[a-z][a-z0-9-]*$/.test(name), `Invalid engine feature: ${name}`);
    return [`engine:feature:${name}`, files];
  }), ['engine:public', manifest.publicFiles], ['engine:tooling', manifest.tooling]];
  const records = [];
  for (const [owner, files] of groups) {
    check(Array.isArray(files), `Invalid file list: ${owner}`);
    for (const file of files) {
      check(file && typeof file === 'object', `Invalid file record: ${owner}`);
      relativePath(file.source, 'source');
      relativePath(file.target, 'target');
      check(!forbiddenSource.test(file.source) && !forbiddenSource.test(file.target), `Test/support/environment input forbidden: ${file.source}`);
      check(!engineSiteSource.test(file.source) && !engineSiteSource.test(file.target), `Site/theme/config/artwork forbidden in engine: ${file.source}`);
      const namespace = owner === 'engine:public' ? 'public/' : owner === 'engine:tooling' ? 'scripts/' : 'src/';
      check(file.target.startsWith(namespace), `Invalid engine target namespace: ${file.target}`);
      check(!targets.has(file.target.toLowerCase()) && !sources.has(file.source.toLowerCase()), `Duplicate engine source/target: ${file.target}`);
      targets.add(file.target.toLowerCase());
      sources.add(file.source.toLowerCase());
      if (file.component !== undefined) {
        check(namespace === 'src/' && /^(?:layouts|widgets|content)\/[a-z0-9][a-z0-9-]*$/.test(file.component), `Invalid component key: ${file.component}`);
        check(!components.has(file.component), `Duplicate component key: ${file.component}`);
        components.add(file.component);
      }
      if (artifact) check(/^[a-f0-9]{64}$/.test(file.sha256 || ''), `Missing artifact hash: ${file.source}`);
      records.push({ ...file, owner });
    }
  }
  return records;
}

function packageConfiguration(source, identity, dependencyRequire) {
  const result = {
    name: identity.name, version: identity.version, private: true,
    license: 'SEE LICENSE IN LICENSE',
    dependencies: {
      ...source.dependencies,
      ...Object.fromEntries(['@babel/parser', '@babel/traverse'].map(name => [name, dependencyRequire(`${name}/package.json`).version])),
    },
    scripts: { build: 'node scripts/build-site.mjs' },
  };
  for (const key of ['devDependencies', 'browserslist', 'eslintConfig']) {
    if (source[key] !== undefined) result[key] = source[key];
  }
  return result;
}

function fingerprint(manifest) {
  const { fingerprint: ignored, ...content } = manifest;
  return hash(JSON.stringify(content));
}

async function copyRecord(sourceRoot, outputRoot, record) {
  const source = await fileAt(sourceRoot, record.source);
  const bytes = await readFile(source);
  const sha256 = hash(bytes);
  if (record.sha256) check(record.sha256 === sha256, `Artifact hash mismatch: ${record.source}`);
  await write(outputRoot, record.target, bytes);
  return { source: record.target, target: record.target, ...(record.component ? { component: record.component } : {}), sha256, origin: record.origin || record.source };
}

function parseRequests(content, filename) {
  let ast;
  try {
    ast = parse(content, { sourceType: 'unambiguous', plugins: ['jsx', ...(filename.endsWith('.ts') || filename.endsWith('.tsx') ? ['typescript'] : [])] });
  } catch (error) {
    throw new Error(`Cannot parse ${filename}: ${error.message}`);
  }
  const requests = [];
  traverse(ast, {
    ImportDeclaration({ node }) { requests.push(node.source.value); },
    ExportNamedDeclaration({ node }) { if (node.source) requests.push(node.source.value); },
    ExportAllDeclaration({ node }) { requests.push(node.source.value); },
    CallExpression({ node }) {
      if (node.callee.type === 'Import') {
        check(node.arguments.length === 1 && node.arguments[0].type === 'StringLiteral', `Nonliteral import forbidden: ${filename}`);
        requests.push(node.arguments[0].value);
      }
      const callee = node.callee;
      check(!(callee.type === 'MemberExpression' && callee.object.type === 'Identifier' && callee.object.name === 'require'), `Context/dynamic require forbidden: ${filename}`);
      if (callee.type === 'Identifier' && callee.name === 'require') {
        check(node.arguments.length === 1 && node.arguments[0].type === 'StringLiteral', `Nonliteral require forbidden: ${filename}`);
        requests.push(node.arguments[0].value);
      }
    },
    enter({ node }) {
      if (node.type === 'ImportExpression') {
        check(node.source.type === 'StringLiteral', `Nonliteral import forbidden: ${filename}`);
        requests.push(node.source.value);
      }
      if (node.type === 'MemberExpression' || node.type === 'OptionalMemberExpression') {
        check(!(node.object.type === 'MetaProperty' && node.object.meta.name === 'import' && node.object.property.name === 'meta'), `Import glob/meta module addressing forbidden: ${filename}`);
      }
    },
    ReferencedIdentifier({ node, parent }) {
      if (node.name === 'require') check(parent.type === 'CallExpression' && parent.callee === node, `Aliased/context require forbidden: ${filename}`);
    },
  });
  return requests;
}

function resolveRequest(from, request, inputs) {
  check(typeof request === 'string' && request && !request.includes('!') && !request.includes('\\') && !request.includes('?') && !request.includes('#'), `Unsupported dependency request in ${from}: ${request}`);
  check(!request.startsWith('/') && !/^[a-z]:/i.test(request), `Absolute dependency forbidden in ${from}`);
  if (!request.startsWith('.')) return null;
  const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(from), request));
  check(resolved.startsWith('src/') && !resolved.startsWith('../'), `Relative dependency escapes app src: ${from} -> ${request}`);
  const candidates = [resolved, ...sourceExtensions.map(extension => `${resolved}${extension}`), ...sourceExtensions.map(extension => `${resolved}/index${extension}`)];
  const target = candidates.find(candidate => inputs.has(candidate));
  check(target, `Missing/unselected dependency: ${from} -> ${request}`);
  return target;
}

async function dependencyClosure(root, records, dependencies = {}) {
  const inputs = new Map(records.filter(file => file.target.startsWith('src/')).map(file => [file.target, file]));
  const edges = [];
  for (const [filename, record] of inputs) {
    if (!codePattern.test(filename)) continue;
    const requests = parseRequests(await readFile(await fileAt(root, filename), 'utf8'), filename);
    for (const request of requests) {
      if ((record.owner === 'engine:core' || record.owner?.startsWith('engine:feature:')) && request.startsWith('.')) {
        const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(filename), request));
        check(!dependency.startsWith('src/sites/'), `Engine imports site source: ${filename} -> ${request}`);
      }
      const target = resolveRequest(filename, request, inputs);
      if (target) {
        const owner = inputs.get(target).owner;
        if (record.owner === 'engine:core') {
          check(!target.startsWith('src/sites/'), `Engine core imports site source: ${filename} -> ${target}`);
          check(!owner.startsWith('engine:feature:'), `Engine core imports optional feature: ${filename} -> ${target}`);
        }
        if (record.owner?.startsWith('engine:feature:')) {
          check(!target.startsWith('src/sites/'), `Engine feature imports site source: ${filename} -> ${target}`);
          check(!owner.startsWith('engine:feature:') || owner === record.owner, `Undeclared cross-feature dependency: ${filename} -> ${target}`);
        }
        edges.push({ from: filename, request, to: target });
      } else {
        const name = request.startsWith('@') ? request.split('/').slice(0, 2).join('/') : request.split('/')[0];
        check(Object.hasOwn(dependencies, name), `Undeclared package dependency: ${filename} -> ${request}`);
        edges.push({ from: filename, request, package: name });
      }
    }
  }
  return edges;
}

/** Export a positive-list local SDK. outputRoot must not exist. No consumer source is read. */
export async function exportEnginePackage({ repoRoot, outputRoot }) {
  repoRoot = path.resolve(repoRoot);
  const manifestBytes = await readFile(await fileAt(repoRoot, 'engine/manifest.json'));
  const manifest = JSON.parse(manifestBytes.toString('utf8'));
  const records = validateRecords(manifest);
  const packageBytes = await readFile(await fileAt(repoRoot, 'package.json'));
  const rootPackage = JSON.parse(packageBytes.toString('utf8'));
  await freshDirectory(outputRoot);
  const copied = new Map();
  for (const record of records) copied.set(record.target, await copyRecord(repoRoot, outputRoot, record));
  const artifact = {
    schemaVersion: 1, name: manifest.name, version: manifest.version,
    core: manifest.core.map(file => copied.get(file.target)),
    features: Object.fromEntries(Object.entries(manifest.features).map(([name, files]) => [name, files.map(file => copied.get(file.target))])),
    publicFiles: manifest.publicFiles.map(file => copied.get(file.target)),
    tooling: manifest.tooling.map(file => copied.get(file.target)),
    originManifest: { source: 'engine/manifest.json', sha256: hash(manifestBytes) },
  };
  const license = await readFile(await fileAt(repoRoot, 'LICENSE'));
  await write(outputRoot, 'LICENSE', license);
  const pkg = json(packageConfiguration(rootPackage, manifest, createRequire(path.join(repoRoot, 'package.json'))));
  await write(outputRoot, 'package.json', pkg);
  artifact.metadata = [
    { source: 'LICENSE', sha256: hash(license), origin: 'LICENSE', originSha256: hash(license) },
    { source: 'package.json', sha256: hash(pkg), origin: 'package.json', originSha256: hash(packageBytes) },
  ];
  artifact.dependencyClosure = await dependencyClosure(outputRoot, validateRecords(artifact, true), rootPackage.dependencies);
  artifact.fingerprint = fingerprint(artifact);
  await write(outputRoot, 'engine.json', json(artifact));
  return { root: outputRoot, manifest: artifact };
}

async function readEngine(engineRoot) {
  const manifest = JSON.parse(await readFile(await fileAt(engineRoot, 'engine.json'), 'utf8'));
  validateRecords(manifest, true);
  check(manifest.fingerprint === fingerprint(manifest), 'Engine manifest fingerprint mismatch');
  check(Array.isArray(manifest.metadata) && manifest.metadata.length === 2, 'Missing engine package metadata');
  for (const filename of ['package.json', 'LICENSE']) {
    const record = manifest.metadata.find(file => file.source === filename);
    check(record && hash(await readFile(await fileAt(engineRoot, filename))) === record.sha256, `Artifact hash mismatch: ${filename}`);
  }
  const pkg = JSON.parse(await readFile(await fileAt(engineRoot, 'package.json'), 'utf8'));
  check(pkg.private === true && pkg.name === manifest.name && pkg.version === manifest.version, 'Engine package identity/private boundary mismatch');
  // Check all features even when this particular consumer does not select them.
  const records = validateRecords(manifest, true);
  for (const record of records) check(hash(await readFile(await fileAt(engineRoot, record.source))) === record.sha256, `Artifact hash mismatch: ${record.source}`);
  return { manifest, pkg };
}

/** Assemble exactly one site's namespace and selected features from an exported SDK. */
export async function assembleSite({ engineRoot, manifestPath, outputRoot }) {
  engineRoot = path.resolve(engineRoot);
  manifestPath = path.resolve(manifestPath);
  await assertNoSymlinks(manifestPath);
  const { manifest, pkg } = await readEngine(engineRoot);
  const siteBytes = await readFile(manifestPath);
  const site = JSON.parse(siteBytes.toString('utf8'));
  check(site?.schemaVersion === 1 && typeof site.id === 'string' && /^[a-z][a-z0-9-]*$/.test(site.id), 'Invalid site descriptor schema/id');
  if (site.language !== undefined) check(typeof site.language === 'string' && /^[a-z]{2,3}(?:-[A-Z]{2}|-[A-Z][a-z]{3})?$/.test(site.language), 'Invalid site language code');
  check(Array.isArray(site.engineFeatures) && new Set(site.engineFeatures).size === site.engineFeatures.length, 'Invalid/duplicate site engineFeatures');
  for (const feature of site.engineFeatures) check(Object.hasOwn(manifest.features, feature), `Unknown engine feature: ${feature}`);
  check(Array.isArray(site.files), 'Invalid site files');
  const selected = [
    ...manifest.core.map(file => ({ ...file, owner: 'engine:core' })),
    ...site.engineFeatures.flatMap(feature => manifest.features[feature].map(file => ({ ...file, owner: `engine:feature:${feature}` }))),
    ...manifest.publicFiles.map(file => ({ ...file, owner: 'engine:public' })),
    ...manifest.tooling.map(file => ({ ...file, owner: 'engine:tooling' })),
  ];
  const targets = new Set(selected.map(file => file.target.toLowerCase()));
  const sources = new Set();
  for (const file of site.files) {
    relativePath(file.source, 'site source');
    relativePath(file.target, 'site target');
    check(file.target.startsWith(`src/sites/${site.id}/`), `Site target must stay in its own namespace: ${file.target}`);
    check(!forbiddenSource.test(file.source) && !forbiddenSource.test(file.target), `Test/support/environment site input forbidden: ${file.source}`);
    check(!targets.has(file.target.toLowerCase()) && !sources.has(file.source.toLowerCase()), `Duplicate site source/target: ${file.target}`);
    targets.add(file.target.toLowerCase());
    sources.add(file.source.toLowerCase());
    if (file.component !== undefined) check(/^(?:layouts|widgets|content)\/[a-z0-9][a-z0-9-]*$/.test(file.component), `Invalid component key: ${file.component}`);
  }
  const components = [...selected, ...site.files].filter(file => file.component);
  check(new Set(components.map(file => file.component)).size === components.length, 'Duplicate component key in selected site/engine');
  await freshDirectory(outputRoot);
  const inputs = [];
  for (const record of selected) {
    const copied = await copyRecord(engineRoot, outputRoot, record);
    inputs.push({ path: record.target, owner: record.owner, sha256: copied.sha256, origin: `engine:${record.origin || record.source}` });
  }
  for (const record of site.files) {
    const copied = await copyRecord(path.dirname(manifestPath), outputRoot, record);
    inputs.push({ path: record.target, owner: `site:${site.id}`, sha256: copied.sha256, origin: record.source });
  }
  if (site.language !== undefined) {
    const indexInput = inputs.find(file => file.path === 'public/index.html');
    check(indexInput, 'Site language requires the engine public/index.html input');
    const indexPath = path.join(outputRoot, 'public/index.html');
    const html = await readFile(indexPath, 'utf8');
    check(/<html\b/i.test(html), 'Site language requires an HTML root element');
    const configured = html.replace(/<html\b[^>]*>/i, tag => /\blang\s*=/i.test(tag)
      ? tag.replace(/\blang\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/i, `lang="${site.language}"`)
      : tag.replace(/>$/, ` lang="${site.language}">`));
    await writeFile(indexPath, configured);
    indexInput.derivedFrom = { owner: indexInput.owner, sha256: indexInput.sha256 };
    indexInput.owner = 'generated:consumer-config';
    indexInput.origin = 'site descriptor language + engine public/index.html';
    indexInput.sha256 = hash(configured);
  }
  const registry = [
    '// Generated for this isolated consumer build. Component keys are explicit manifest data.',
    ...components.map((file, index) => `import Component${index} from ${JSON.stringify(`./${file.target.slice(4)}`)};`),
    'const componentLoaders = {',
    ...components.map((file, index) => `  ${JSON.stringify(file.component)}: () => Component${index},`),
    '};', 'export default componentLoaders;', '',
  ].join('\n');
  await write(outputRoot, 'src/component-loaders.js', registry);
  const existingRegistry = inputs.findIndex(file => file.path === 'src/component-loaders.js');
  if (existingRegistry >= 0) inputs.splice(existingRegistry, 1);
  inputs.push({ path: 'src/component-loaders.js', owner: 'generated:registry', sha256: hash(registry), origin: 'selected manifest component keys' });
  const consumerPackage = { ...pkg, name: `${site.id}-local-consumer`, private: true, scripts: { build: 'react-scripts build' } };
  const packageBytes = json(consumerPackage);
  await write(outputRoot, 'package.json', packageBytes);
  inputs.push({ path: 'package.json', owner: 'generated:package', sha256: hash(packageBytes), origin: 'engine package configuration', derivedFrom: { owner: 'engine:metadata', sha256: manifest.metadata.find(file => file.source === 'package.json').sha256 } });
  const dependencyRecords = inputs.map(file => ({ ...file, target: file.path }));
  const dependencyGraph = await dependencyClosure(outputRoot, dependencyRecords, pkg.dependencies);
  return {
    root: outputRoot, engineRoot, site: site.id, language: site.language, engineVersion: manifest.version, engineFingerprint: manifest.fingerprint,
    selectedFeatures: [...site.engineFeatures], allowInitialHeader: site.allowInitialHeader === true,
    descriptorSha256: hash(siteBytes), componentKeys: components.map(file => file.component), inputs,
    dependencyClosure: dependencyGraph,
  };
}

async function listFiles(root, relative = '') {
  const files = [];
  for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
    const name = relative ? `${relative}/${entry.name}` : entry.name;
    check(!entry.isSymbolicLink(), `Symlink in public output: ${name}`);
    if (entry.isDirectory()) files.push(...await listFiles(root, name));
    else { check(entry.isFile(), `Unexpected public output type: ${name}`); files.push(name); }
  }
  return files;
}

/** Verify webpack's recursive ALL-chunk graph, then inspect the actual public output. */
export async function verifyBuildGraph({ stats, assembly, outputRoot }) {
  const violations = [];
  const selected = new Set(assembly.inputs.map(file => file.path));
  const root = slash(path.resolve(assembly.root)).replace(/\/$/, '');
  const compare = value => process.platform === 'win32' ? value.toLowerCase() : value;
  const normalizedRoot = compare(root);
  let moduleCount = 0;
  let chunkCount = 0;
  const seen = new Set();
  const emitted = new Set();
  function inspectResource(raw) {
    const value = slash(raw).replace(/\0/g, '');
    if (/\b(?:sync|lazy|eager|weak)\b.*(?:recursive|nonrecursive)|\b(?:sync|lazy)\s+\^|\|(?:sync|lazy|eager|weak)\|/.test(value) && /(?:\.\/src\/|\/src\/)/.test(value)) violations.push(`Context module from app source: ${value}`);
    for (let part of value.split('!')) {
      part = part.replace(/\?.*$/, '').replace(/ \+ \d+ modules$/, '');
      // Webpack prefixes identifiers with their module type, e.g. javascript/esm|.
      part = part.slice(part.lastIndexOf('|') + 1);
      if (part.includes('/node_modules/') || part.startsWith('./node_modules/')) continue;
      let resource;
      const absolute = compare(part);
      if (absolute.startsWith(`${normalizedRoot}/`)) resource = part.slice(root.length + 1);
      else if (part.startsWith('./src/') || part.startsWith('./public/')) resource = part.slice(2);
      else if (/^(?:src|public)\//.test(part)) resource = part;
      else if (/(?:^|\/)(?:src|public)\//.test(part)) violations.push(`Foreign app resource: ${part}`);
      if (resource && !selected.has(resource)) violations.push(`Unselected app resource: ${resource}`);
    }
  }
  function visitModule(module) {
    const key = module.identifier || module.name || module;
    if (seen.has(key)) return;
    seen.add(key);
    moduleCount++;
    for (const key of ['identifier', 'name', 'nameForCondition']) if (typeof module[key] === 'string') inspectResource(module[key]);
    for (const child of module.modules || []) visitModule(child);
  }
  function visitCompilation(compilation) {
    function visitAsset(asset) {
      if (typeof asset.name === 'string' && !asset.children?.length) emitted.add(slash(asset.name));
      for (const child of asset.children || []) visitAsset(child);
      for (const related of asset.related || []) visitAsset(related);
      for (const name of Object.values(asset.info?.related || {}).flat()) {
        if (typeof name === 'string') emitted.add(slash(name));
      }
    }
    for (const asset of compilation.assets || []) visitAsset(asset);
    for (const module of compilation.modules || []) visitModule(module);
    for (const chunk of compilation.chunks || []) {
      chunkCount++;
      for (const file of [...(chunk.files || []), ...(chunk.auxiliaryFiles || [])]) emitted.add(slash(file));
      for (const module of chunk.modules || []) visitModule(module);
    }
    for (const child of compilation.children || []) visitCompilation(child);
  }
  check(stats && typeof stats === 'object', 'Missing webpack stats');
  visitCompilation(stats);
  check(moduleCount > 0 && chunkCount > 0, 'Webpack stats must contain modules and chunks for boundary proof');
  if (stats.errors?.length) violations.push('Webpack stats report compilation errors');
  const allowedOutput = new Set([
    ...emitted, 'index.html', 'asset-manifest.json',
    ...assembly.inputs.filter(file => file.path.startsWith('public/')).map(file => file.path.slice(7)),
    ...(assembly.allowInitialHeader ? ['reader-initial/desktop.png', 'reader-initial/desktop2x.png', 'reader-initial/mobile.png', 'reader-initial/mobile2x.png', 'reader-initial/theme.css'] : []),
  ]);
  const outputFiles = await listFiles(outputRoot);
  for (const name of outputFiles) {
    if (!allowedOutput.has(name)) violations.push(`Unselected/unemitted public asset: ${name}`);
    if (/(?:^|\/)(?:src|tests?|test-support|fixtures?|node_modules)(?:\/|$)|(?:^|\/)\.env(?:\.|$)|(?:^|\/)(?:bundle-stats|engine|provenance|build-proof|site)\.json$|\.(?:map|jsx|tsx?|mjs|cjs)$/i.test(name)) violations.push(`Private/source evidence in public output: ${name}`);
    if (name.endsWith('.js') && !name.startsWith('static/')) violations.push(`Unexpected source JavaScript in public output: ${name}`);
  }
  const output = [];
  for (const name of outputFiles) output.push({ path: name, sha256: hash(await readFile(path.join(outputRoot, name))) });
  const proof = {
    schemaVersion: 1, site: assembly.site, siteId: assembly.site, engineVersion: assembly.engineVersion, engineFingerprint: assembly.engineFingerprint,
    selectedFeatures: assembly.selectedFeatures, descriptorSha256: assembly.descriptorSha256,
    inputs: assembly.inputs, componentKeys: assembly.componentKeys, dependencyClosure: assembly.dependencyClosure,
    moduleCount, chunkCount, output, violations: [...new Set(violations)],
  };
  if (proof.violations.length) {
    const error = new Error(`Build boundary verification failed:\n${proof.violations.join('\n')}`);
    error.proof = proof;
    throw error;
  }
  return proof;
}

/** Public output is limited to the caller's build directory or an ignored temp descendant. */
export async function validateBuildOutput(cwd, outputRoot) {
  check(path.isAbsolute(outputRoot), '--output must be absolute');
  const output = path.resolve(outputRoot);
  check(output === path.resolve(cwd, 'build') || (within(path.resolve(cwd, 'temp'), output) && output !== path.resolve(cwd, 'temp')), 'Build output must be cwd/build or a cwd/temp descendant');
  await assertNoSymlinks(output);
  return output;
}

export async function ensureEmptyOutput(outputRoot) {
  await assertNoSymlinks(outputRoot);
  try {
    check((await lstat(outputRoot)).isDirectory(), 'Build output is not a directory');
    check((await readdir(outputRoot)).length === 0, 'Build output must be fresh or empty; choose a new ignored temp path');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    await mkdir(outputRoot, { recursive: true });
  }
}

/** Hash approved external build inputs without copying them into the SDK/public input. */
export async function readInitialHeaderInputs({ configPath, site, excludedRoots = [] }) {
  if (!configPath) return [];
  async function input(filename, extension, role, outputPath) {
    check(typeof filename === 'string' && path.isAbsolute(filename) && path.extname(filename).toLowerCase() === extension, `Initial header ${role} must be an absolute ${extension} file`);
    check(!forbiddenSource.test(path.basename(filename)), 'Credential/environment input forbidden for initial header');
    check(!excludedRoots.some(root => within(root, filename)), 'Initial header inputs must be external to engine/assembled/evidence/public output');
    await assertNoSymlinks(filename);
    check((await lstat(filename)).isFile(), 'Initial header input is not a regular file');
    const bytes = await readFile(filename);
    return { bytes, record: { path: path.resolve(filename), owner: `site:${site}:initial-header`, role, sha256: hash(bytes), ...(outputPath ? { outputPath } : {}) } };
  }
  const configInput = await input(configPath, '.json', 'configuration');
  const config = JSON.parse(configInput.bytes.toString('utf8'));
  const records = [configInput.record];
  for (const key of ['desktop', 'desktop2x', 'mobile', 'mobile2x', 'theme']) {
    const extension = key === 'theme' ? '.css' : '.png';
    records.push((await input(config[key], extension, key, `reader-initial/${key}${extension}`)).record);
  }
  return records;
}
