test('build proof allows exact compiler-related license assets while rejecting an unrelated license filename', async () => {
  const { assembly, root } = await assembled();
  const outputRoot = await publicBuild(root);
  const license = 'static/js/main.hash.js.LICENSE.txt';
  await put(outputRoot, license, 'Retained upstream license notice');
  const stats = statsFor(assembly);
  stats.assets[0].info = { related: { license } };
  stats.assets[0].related = [{ type: 'license', name: license, info: { extractedComments: true }, related: [] }];
  assert.deepEqual((await verifyBuildGraph({ stats, assembly, outputRoot })).violations, []);
  delete stats.assets[0].related;
  assert.deepEqual((await verifyBuildGraph({ stats, assembly, outputRoot })).violations, []);
  await put(outputRoot, 'static/js/foreign.hash.js.LICENSE.txt', 'Not emitted or selected');
  await assert.rejects(verifyBuildGraph({ stats, assembly, outputRoot }), /Unselected\/unemitted public asset: static\/js\/foreign.hash.js.LICENSE.txt/);
});

